const assert=require('node:assert/strict');
const I=require('../../integrations/core.js');
const row={external_id:'0001',building_code:'S-001',status:'open',updated_at:'2026-11-05T09:00:00+03:00',description:'test'};
const norm=(r)=>I.normalize('tickets','tickets-a',[r]);
let data=I.apply([],I.plan([],norm(row)));
assert.equal(data[0].external_id,'0001');
assert.equal(I.plan(data,norm(row))[0].action,'unchanged');
assert.equal(I.plan(data,norm({...row,status:'closed'}))[0].action,'conflict');
assert.equal(I.plan(data,norm({...row,status:'closed',updated_at:'2026-11-04T09:00:00Z'}))[0].action,'stale');
assert.equal(I.plan(data,[...norm(row),...norm(row)])[0].action,'duplicate');
assert.equal(I.apply(data,I.plan(data,norm({...row,status:'closed',updated_at:'2026-11-06T09:00:00Z'})))[0].status,'closed');
assert.equal(I.apply(data,[]).length,1);
assert.equal(I.plan(data,I.normalize('tickets','tickets-b',[row]))[0].action,'new');
assert.throws(()=>norm({...row,updated_at:'2026-11-05T09:00:00'}));
assert.equal(I.csv('a,b\r\n"hello, world","line1\nline2"')[0].b,'line1\nline2');
assert.throws(()=>I.csv('a,a\n1,2'));
const m={external_id:'m1',ticket_external_id:'0001',item_code:'009',warehouse:'R',type:'issue',quantity:2,unit_cost:10,updated_at:row.updated_at};
const mov=(v)=>I.normalize('movements','warehouse-a',[v]);
let movements=I.apply([],I.plan([],mov(m)));
movements=I.apply(movements,I.plan(movements,mov(m)));
assert.equal(I.costs(movements,'warehouse-a'),20);
movements=I.apply(movements,I.plan(movements,mov({...m,external_id:'m2',type:'return',quantity:1})));
assert.equal(I.costs(movements,'warehouse-a'),10);
movements=I.apply(movements,I.plan(movements,mov({...m,type:'cancelled',updated_at:'2026-11-06T09:00:00Z'})));
assert.equal(I.costs(movements,'warehouse-a'),-10);
assert.throws(()=>mov({...m,quantity:-1}));
assert.throws(()=>mov({...m,unit_cost:'Infinity'}));
console.log('V331 core: passed');
